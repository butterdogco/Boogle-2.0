/**
 * Searches the results array for matches based on the query.
 * The search is case-insensitive and checks for matches in the name, description, and keywords.
 * @param {string} query
 * @returns {Array} An array of matching results.
 */
export function findResultsByQuery(query) {
  const lowerCaseQuery = query.toLowerCase();
  return results.filter(result => {
    const nameMatch = result.name.toLowerCase().includes(lowerCaseQuery);
    const descriptionMatch = result.description.toLowerCase().includes(lowerCaseQuery);
    const keywordsMatch = result.keywords.some(keyword => keyword.toLowerCase().includes(lowerCaseQuery));
    const autocompletionsMatch = result.autocompletions && result.autocompletions.some(suggestion => suggestion.toLowerCase().includes(lowerCaseQuery));
    return nameMatch || descriptionMatch || keywordsMatch || autocompletionsMatch;
  });
}

/**
 * Searches the specialResults array for a match based on the query.
 * The search is case-insensitive and checks if any of the triggers are included in the query.
 * @param {string} query
 * @returns {string|null} The result of the action if a match is found, otherwise null.
 */
export function findSpecialResultByQuery(query) {
  const lowerCaseQuery = query.toLowerCase();
  for (const specialResult of specialResults) {
    if (specialResult.triggers.some(trigger => lowerCaseQuery.includes(trigger))) {
      return specialResult.action();
    }
  }

  return null;
}

/**
 * Provides autocomplete suggestions based on the query.
 * The suggestions are derived from the name, description, and keywords of the results.
 * @param {string} query
 * @param {number} [limit=5] - The maximum number of suggestions to return.
 * @returns {Array<String>} An array of unique suggestions.
 */
export function getAutocompleteSuggestions(query, limit = 5) {
  const lowerCaseQuery = query.toLowerCase();
  const suggestions = new Set();

  results.forEach(result => {
    if (result.autocompletions) {
      result.name.toLowerCase().includes(lowerCaseQuery) && suggestions.add(result.name.toLowerCase());
      result.autocompletions.forEach(suggestion => {
        if (suggestion.toLowerCase().includes(lowerCaseQuery)) {
          suggestions.add(suggestion);
        }
      });
    }
  });

  return Array.from(suggestions).slice(0, limit);
}

/**
 * Returns a random search query from the autocompletions of all results.
 * @returns {string} A random search query.
 */
export function getRandomSearchQuery() {
  const allAutocompletions = results.flatMap(result => result.autocompletions || []);
  const randomIndex = Math.floor(Math.random() * allAutocompletions.length);
  return allAutocompletions[randomIndex];
}